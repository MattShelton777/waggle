// Bundle @waggle/server (+ core, zod, MCP SDK) into one ESM file the Edge
// Function imports. Deno can't resolve this npm workspace, so we ship a bundle.
import { build } from "esbuild";

await build({
  entryPoints: ["packages/server/src/index.ts"],
  outfile: "supabase/functions/mcp/waggle.bundle.js",
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  mainFields: ["module", "main"],
  conditions: ["deno", "worker", "browser", "import", "default"],
  external: ["node:*"],
  legalComments: "none",
  banner: { js: "// Generated by scripts/build-functions.mjs. Do not edit." },
});
console.log("built supabase/functions/mcp/waggle.bundle.js");
