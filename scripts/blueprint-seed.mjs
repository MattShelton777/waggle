// Turn seed/blueprints/*.json into an append-only seed migration.
// Usage: node scripts/blueprint-seed.mjs supabase/migrations/<version>_waggle_seed_blueprints.sql
// Each seed file is { "vendor_domains": [...], "blueprint": { ... } }. packages/core/test/blueprint.test.ts
// validates every file, and supabase/test/blueprint-seed.test.ts checks the committed migration matches this output.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const quote = (s) => {
  let tag = "bp";
  while (s.includes("$" + tag + "$")) tag += "x";
  return "$" + tag + "$" + s + "$" + tag + "$";
};

export function blueprintSeedSql(dir = "seed/blueprints") {
  const files = readdirSync(dir).filter((f) => f.endsWith(".json")).sort();
  const parts = ["-- Generated by scripts/blueprint-seed.mjs from seed/blueprints/*.json. Do not edit by hand.", ""];
  for (const f of files) {
    const { vendor_domains, blueprint } = JSON.parse(readFileSync(join(dir, f), "utf8"));
    const slug = blueprint.entity;
    if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) throw new Error(`bad slug in ${f}`);
    parts.push(
      `-- ${slug}`,
      `update waggle.entities set attributes = attributes || jsonb_build_object('vendor_domains', ${quote(JSON.stringify(vendor_domains))}::jsonb) where slug = '${slug}';`,
      "insert into waggle.blueprints (entity_id, version, body, origin, status)",
      `select e.id, coalesce((select max(b.version) from waggle.blueprints b where b.entity_id = e.id), 0) + 1, ${quote(JSON.stringify(blueprint))}::jsonb, 'curated', 'accepted'`,
      `from waggle.entities e where e.slug = '${slug}' and e.type in ('tool', 'workflow');`,
      "",
    );
  }
  return parts.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = process.argv[2];
  if (!out) throw new Error("usage: node scripts/blueprint-seed.mjs <migration file>");
  writeFileSync(out, blueprintSeedSql());
  console.log(`wrote ${out}`);
}
